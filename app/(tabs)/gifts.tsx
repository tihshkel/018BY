export default function GiftsScreen() {
  const layout = useResponsiveLayout(CATALOG_MAX_WIDTH);
  const numColumns = !layout.isTablet ? 1 : layout.width >= 1000 ? 3 : 2;
  const coverHeight = numColumns === 1 ? 280 : numColumns === 2 ? 220 : 200;

  const insets = useSafeAreaInsets();
  const bottomInset = Math.max(insets.bottom, Platform.OS === 'ios' ? 32 : 20);
  const [searchQuery, setSearchQuery] = useState('');
  const [activeCategory, setActiveCategory] =
    useState<CategoryFilter>('Все');
  const [showFilterModal, setShowFilterModal] = useState(false);
  const [selectedCategory, setSelectedCategory] = useState<CategoryFilter | null>(null);
  const [selectedCoverType, setSelectedCoverType] = useState<CoverType>('all');
  const [selectedRegion, setSelectedRegion] = useState<Region | null>(null);
  const [showRegionModal, setShowRegionModal] = useState(false);
  const [isLoadingRegion, setIsLoadingRegion] = useState(true);

  const opacity = useSharedValue(0);

  // Предзагрузка карточек WB после первого кадра — не мешает скроллу
  useFocusEffect(
    React.useCallback(() => {
      const task = InteractionManager.runAfterInteractions(() => {
        prefetchWildberriesProductInfo(
          GIFT_ITEMS.map((gift) => gift.link),
          32,
        ).catch((error) => {
          console.warn('⚠️ Ошибка предзагрузки карточек WB:', error);
        });
      });

      return () => task.cancel();
    }, [])
  );

  useEffect(() => {
    opacity.value = withTiming(1, { duration: 350 });
  }, [opacity]);

  // Загружаем сохраненный регион при монтировании
  useEffect(() => {
    const loadRegion = async () => {
      try {
        const savedRegion = await AsyncStorage.getItem('@user_region');
        if (savedRegion) {
          const region = savedRegion as Region;
          setSelectedRegion(region);
          setIsLoadingRegion(false);
        } else {
          // Если регион не выбран, показываем модальное окно
          setIsLoadingRegion(false);
          setShowRegionModal(true);
        }
      } catch (error) {
        console.error('Error loading region:', error);
        setIsLoadingRegion(false);
        setShowRegionModal(true);
      }
    };
    loadRegion();
  }, []);

  // Сохраняем выбранный регион
  const handleRegionSelect = async (region: Region) => {
    try {
      await AsyncStorage.setItem('@user_region', region);
      setSelectedRegion(region);
      setShowRegionModal(false);
    } catch (error) {
      console.error('Error saving region:', error);
    }
  };


  const animatedStyle = useAnimatedStyle(() => ({
    opacity: opacity.value,
  }));

  const handleChangeSearch = useCallback((value: string) => {
    setSearchQuery(value);
  }, []);

  const handleSelectCategory = useCallback((filter: CategoryFilter) => {
    setActiveCategory(filter);
  }, []);

  const handleOpenLink = useCallback(async (url: string) => {
    try {
      const canOpen = await Linking.canOpenURL(url);
      if (!canOpen) {
        return;
      }
      await Linking.openURL(url);
    } catch (error) {
      console.error('Не удалось открыть ссылку:', error);
    }
  }, []);

  const filteredItems = useMemo(() => {
    const normalizedQuery = searchQuery.trim().toLowerCase();
    
    // Определяем категорию для фильтрации (приоритет у расширенного поиска)
    const filterCategory = selectedCategory || (activeCategory === 'Все' ? null : activeCategory);
    
    return GIFT_ITEMS.filter(item => {
      // Фильтр по поисковому запросу
      const matchesSearch =
        normalizedQuery.length === 0 ||
        item.title.toLowerCase().includes(normalizedQuery) ||
        item.sku.toLowerCase().includes(normalizedQuery);
      if (!matchesSearch) {
        return false;
      }
      
      // Фильтр по категории (если выбрана)
      if (filterCategory) {
        // Проверяем специальный маппинг по SKU (для "Для девочек")
        const skuCategory = SKU_TO_CATEGORY[item.sku];
        if (skuCategory === filterCategory) {
          // Продолжаем проверку типа обложки
        } else if (item.celebrations.includes(filterCategory)) {
          // Товары из PDF-каталога и новые позиции с прямым совпадением категории
        } else {
          // Маппинг категорий на старые названия celebrations
          const categoryToCelebrations: Record<string, string[]> = {
            'Будущим мамам': ['Беременность', 'Будущим мамам'],
            'В подарок': ['День рождения', 'В подарок'],
            'Для новорождённых': ['Выписка', 'Первый год', 'Для новорождённых'],
            'Молодожёнам': ['Молодожёнам'],
            'Для семьи': ['Для семьи'],
            'Для детей': ['Для детей'],
          };

          if (filterCategory === 'Молодожёнам') {
            const matches =
              item.sku.startsWith('SVA') ||
              item.sku.startsWith('SA') ||
              item.sku.startsWith('SVO') ||
              item.sku.startsWith('SB') ||
              item.celebrations.includes('Молодожёнам');
            if (!matches) return false;
          } else if (filterCategory === 'В подарок') {
            const isGirlsDiary = SKU_TO_CATEGORY[item.sku] === 'Для девочек';
            const matches =
              (item.celebrations.includes('День рождения') ||
                item.celebrations.includes('В подарок')) &&
              !isGirlsDiary;
            if (!matches) return false;
          } else {
            const celebrationsToMatch = categoryToCelebrations[filterCategory] || [];
            if (celebrationsToMatch.length > 0) {
              const matches = item.celebrations.some((celeb) =>
                celebrationsToMatch.includes(celeb)
              );
              if (!matches) return false;
            }
          }
        }
      }
      
      // Фильтр по типу обложки
      if (selectedCoverType !== 'all') {
        const coverType = getCoverType(item.title);
        if (selectedCoverType === 'hard') {
          if (coverType !== 'hard') return false;
        } else if (selectedCoverType === 'soft') {
          if (coverType !== 'soft') return false;
        }
      }
      
      return true;
    });
  }, [searchQuery, activeCategory, selectedCategory, selectedCoverType]);

  // Предзагрузка карточек для отфильтрованных элементов — после анимаций
  useEffect(() => {
    const task = InteractionManager.runAfterInteractions(() => {
      prefetchWildberriesProductInfo(
        filteredItems.map((item) => item.link),
        24,
      ).catch(() => {});
    });

    return () => task.cancel();
  }, [filteredItems]);

  const renderFilter = useCallback(
    (filter: CategoryFilter) => {
      const isActive = filter === activeCategory;
      return (
        <Pressable
          key={filter}
          accessibilityRole="button"
          accessibilityState={{ selected: isActive }}
          accessibilityLabel={`Категория ${filter}`}
          style={({ pressed }) => [
            styles.categoryFilterButton,
            isActive && styles.categoryFilterButtonActive,
            pressed && styles.categoryFilterButtonPressed,
          ]}
          onPress={() => handleSelectCategory(filter)}
        >
          <Text
            style={[
              styles.filterButtonText,
              isActive && styles.filterButtonTextActive,
            ]}
          >
            {filter}
          </Text>
        </Pressable>
      );
    },
    [activeCategory, handleSelectCategory]
  );


  const renderItem = useCallback(
    ({ item, index }: { item: GiftItem; index: number }) => (
      <MemoGiftCatalogCard
        item={item}
        index={index}
        numColumns={numColumns}
        coverHeight={coverHeight}
        onOpenLink={handleOpenLink}
      />
    ),
    [handleOpenLink, numColumns, coverHeight]
  );

  const contentShellStyle = layout.isTablet
    ? {
        width: '100%' as const,
        maxWidth: layout.contentMaxWidth + layout.horizontalPadding * 2,
        alignSelf: 'center' as const,
        paddingHorizontal: layout.horizontalPadding,
      }
    : undefined;

  return (
    // В табах нижний safe-area уже учитывается таббаром; bottom-edge даёт “пустую полосу” над панелью.
    <SafeAreaView style={styles.container} edges={['top']}>
      <Animated.View style={[styles.content, contentShellStyle, animatedStyle]}>
        <View style={styles.titleContainer}>
          <Text style={styles.title}>
            Каталог
            {(selectedCategory !== null || selectedCoverType !== 'all') && (
              <Text style={styles.titleCount}> ({filteredItems.length})</Text>
            )}
          </Text>
        </View>

        <View style={styles.searchContainer}>
          <View style={styles.searchWrapper}>
            <Ionicons name="search-outline" size={18} color={colors.textSecondary} />
            <TextInput
              style={styles.searchInput}
              placeholder="Поиск по названию или артикулу"
              placeholderTextColor="#C7BBB0"
              value={searchQuery}
              onChangeText={handleChangeSearch}
              returnKeyType="search"
              accessibilityLabel="Поиск подарков"
              accessibilityHint="Введите название товара или артикул"
            />
          </View>
          <TouchableOpacity
            style={styles.filterButton}
            onPress={() => setShowFilterModal(true)}
            activeOpacity={0.7}
            accessibilityRole="button"
            accessibilityLabel="Расширенный поиск"
          >
            <Ionicons 
              name="filter-outline" 
              size={20} 
              color={(selectedCategory !== null || selectedCoverType !== 'all') ? colors.primary : colors.textSecondary} 
            />
            {(selectedCategory !== null || selectedCoverType !== 'all') && (
              <View style={styles.filterActiveIndicator} />
            )}
          </TouchableOpacity>
        </View>

        <View style={styles.filtersRow}>
          <FlatList
            horizontal
            data={CATEGORY_FILTERS}
            renderItem={({ item }) => renderFilter(item)}
            keyExtractor={item => item}
            showsHorizontalScrollIndicator={false}
            contentContainerStyle={styles.filtersContent}
          />
        </View>

        <FlatList
          key={`catalog-cols-${numColumns}`}
          data={filteredItems}
          keyExtractor={item => item.id}
          renderItem={renderItem}
          numColumns={numColumns}
          columnWrapperStyle={numColumns > 1 ? styles.catalogColumnWrapper : undefined}
          showsVerticalScrollIndicator={false}
          contentContainerStyle={[styles.listContent, { paddingBottom: bottomInset + 140 }]}
          removeClippedSubviews={Platform.OS === 'android'}
          initialNumToRender={numColumns > 1 ? 4 : 3}
          maxToRenderPerBatch={numColumns > 1 ? 4 : 2}
          updateCellsBatchingPeriod={100}
          windowSize={7}
          ListEmptyComponent={
            <View style={styles.emptyState}>
              <Ionicons name="gift-outline" size={64} color={colors.tabInactive} />
              <Text style={styles.emptyStateText}>
                Подходящие подарки не найдены. Попробуйте изменить запрос.
              </Text>
            </View>
          }
        />
      </Animated.View>

      <AppFilterSheet
        visible={showFilterModal}
        onClose={() => setShowFilterModal(false)}
        title="Расширенный поиск"
        sections={[
          {
            id: 'category',
            title: 'Раздел',
            options: CATEGORY_FILTERS.map((category) => ({
              value: category,
              label: category,
            })),
            value: selectedCategory ?? 'Все',
            onChange: (value) =>
              setSelectedCategory(value === 'Все' ? null : (value as CategoryFilter)),
          },
          {
            id: 'cover',
            title: 'Тип обложки',
            options: [
              { value: 'all', label: 'Все' },
              { value: 'hard', label: 'Твердая обложка' },
              { value: 'soft', label: 'Мягкая обложка' },
            ],
            value: selectedCoverType,
            onChange: (value) => setSelectedCoverType(value as CoverType),
          },
        ]}
        onReset={() => {
          setSelectedCategory(null);
          setSelectedCoverType('all');
        }}
        onApply={() => setShowFilterModal(false)}
      />

      <RegionPickerSheet
        visible={showRegionModal && !isLoadingRegion}
        onClose={() => {}}
        options={REGIONS}
        selectedValue={selectedRegion}
        onSelect={handleRegionSelect}
      />
    </SafeAreaView>
  );
}

