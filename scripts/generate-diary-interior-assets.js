/**
 * Regenerates utils/diaryInteriorAssets.generated.ts with NFC folder names.
 * Avoids NFD "й" (и + combining breve) paths that break Android Metro resolve.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const brownDir = path.join(
  'albums',
  'diary',
  'cover',
  'in album',
  'Блок коричневый _180х240_print'
);
const purpleDir = path.join(
  'albums',
  'diary',
  'cover',
  'in album',
  'Блок фиолетовый_180х240_print'
);

function pageRequires(dirRel, count) {
  const lines = [];
  for (let i = 1; i <= count; i += 1) {
    const name = `page_${String(i).padStart(3, '0')}.png`;
    const rel = path.posix.join('..', dirRel.split(path.sep).join('/'), name);
    lines.push(`  require('${rel}'),`);
  }
  return lines.join('\n');
}

const outPath = path.join(root, 'utils', 'diaryInteriorAssets.generated.ts');
const content = `/** Auto-generated by scripts/generate-diary-interior-assets.js — do not edit by hand */
import type { ImageSourcePropType } from 'react-native';

export const DIARY_BROWN_PAGES: ImageSourcePropType[] = [
${pageRequires(brownDir, 60)}
];

export const DIARY_PURPLE_PAGES: ImageSourcePropType[] = [
${pageRequires(purpleDir, 40)}
];
`;

fs.writeFileSync(outPath, content, 'utf8');
const hasNfd = content.includes('\u0306');
console.log(`Wrote ${outPath} (${hasNfd ? 'HAS_NFD' : 'NFC_OK'})`);
