#!/usr/bin/env node
/**
 * Сканирует PNG страниц дневников и генерирует utils/diaryInteriorAssets.generated.ts
 * Имена папок — из fs.readdirSync (NFC/NFD на macOS).
 * Запуск: node scripts/generate-diary-interior-assets.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const coverRoot = path.join(root, 'albums/diary/cover/in album');

function findBlockDir(predicate) {
  const name = fs.readdirSync(coverRoot).find(predicate);
  if (!name) {
    throw new Error(`Не найдена папка блока в ${coverRoot}`);
  }
  return name;
}

const brownDir = findBlockDir((d) => d.includes('корич'));
const purpleDir = findBlockDir((d) => d.includes('фиолет'));

const blocks = [
  { exportName: 'DIARY_BROWN_PAGES', dirName: brownDir },
  { exportName: 'DIARY_PURPLE_PAGES', dirName: purpleDir },
];

let out = `/** Auto-generated by scripts/generate-diary-interior-assets.js — do not edit by hand */\nimport type { ImageSourcePropType } from 'react-native';\n\n`;

for (const block of blocks) {
  const dir = path.join(coverRoot, block.dirName);
  const files = fs
    .readdirSync(dir)
    .filter((f) => /^page_\d+\.png$/i.test(f))
    .sort((a, b) => parseInt(a.match(/\d+/)?.[0] || '0', 10) - parseInt(b.match(/\d+/)?.[0] || '0', 10));

  const relDir = `../albums/diary/cover/in album/${block.dirName}`;
  out += `export const ${block.exportName}: ImageSourcePropType[] = [\n`;
  for (const f of files) {
    out += `  require('${relDir}/${f}'),\n`;
  }
  out += `];\n\n`;
  console.log(`${block.exportName}: ${files.length} pages ← ${JSON.stringify(block.dirName)}`);
}

const outPath = path.join(root, 'utils/diaryInteriorAssets.generated.ts');
fs.writeFileSync(outPath, out);
console.log('Written', outPath);
