/**
 * Regenerates utils/diaryInteriorAssets.generated.ts with ASCII folder paths.
 * Cyrillic paths under albums/diary/cover/in album break Android asset packing
 * (pages collide / only first page loads). Use albums/diary/interiors/{brown,purple}.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const brownDir = path.join('albums', 'diary', 'interiors', 'brown');
const purpleDir = path.join('albums', 'diary', 'interiors', 'purple');

function assertPages(dirRel, count) {
  const abs = path.join(root, dirRel);
  if (!fs.existsSync(abs)) {
    throw new Error(`Missing diary interior dir: ${abs}. Run scripts/copy-diary-interiors-ascii.py`);
  }
  for (let i = 1; i <= count; i += 1) {
    const name = `page_${String(i).padStart(3, '0')}.png`;
    const file = path.join(abs, name);
    if (!fs.existsSync(file)) {
      throw new Error(`Missing ${file}`);
    }
  }
}

function pageRequires(dirRel, count) {
  const lines = [];
  for (let i = 1; i <= count; i += 1) {
    const name = `page_${String(i).padStart(3, '0')}.png`;
    const rel = path.posix.join('..', dirRel.split(path.sep).join('/'), name);
    lines.push(`  require('${rel}'),`);
  }
  return lines.join('\n');
}

assertPages(brownDir, 60);
assertPages(purpleDir, 40);

const outPath = path.join(root, 'utils', 'diaryInteriorAssets.generated.ts');
const content = `/** Auto-generated by scripts/generate-diary-interior-assets.js - do not edit by hand */
import type { ImageSourcePropType } from 'react-native';

export const DIARY_BROWN_PAGES: ImageSourcePropType[] = [
${pageRequires(brownDir, 60)}
];

export const DIARY_PURPLE_PAGES: ImageSourcePropType[] = [
${pageRequires(purpleDir, 40)}
];
`;

fs.writeFileSync(outPath, content, 'utf8');
console.log(`Wrote ${outPath} (ASCII paths, NFC_OK)`);
