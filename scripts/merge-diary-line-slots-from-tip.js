const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const tip = '6858f3d';

function gitShow(file) {
  return execSync(`git show ${tip}:${file}`, {
    maxBuffer: 80 * 1024 * 1024,
    encoding: 'utf8',
  });
}

// --- line-slots.json: keep pregnancy/kids from current, diaries from tip ---
const currentJson = JSON.parse(
  fs.readFileSync(path.join(root, 'constants/line-slots.json'), 'utf8'),
);
const tipJson = JSON.parse(gitShow('constants/line-slots.json'));

for (const album of ['diary_interior_brown', 'diary_interior_purple']) {
  if (!tipJson[album]) throw new Error(`Missing ${album} in tip`);
  currentJson[album] = tipJson[album];
  console.log('merged line-slots.json', album, Object.keys(tipJson[album]).length, 'pages');
}

fs.writeFileSync(
  path.join(root, 'constants/line-slots.json'),
  JSON.stringify(currentJson, null, 2) + '\n',
);

// --- line-slots.ts: regenerate from JSON preserving header ---
const header = `// Auto-generated by scripts/generate-line-slots.js
// Do not edit manually.

export type NormalizedLineSlot = {
  x: number;
  y: number;
  width: number;
  height: number;
  hasLabel: boolean;
  continuationGroup: number;
  inputKind?: 'line' | 'block';
  textAnchorTop?: boolean;
  lineStrokeAtBottom?: boolean;
};

export const LINE_SLOTS = `;

fs.writeFileSync(
  path.join(root, 'constants/line-slots.ts'),
  header + JSON.stringify(currentJson, null, 2) + ' as const;\n',
);
console.log('wrote constants/line-slots.ts');

// Verify pregnancy/kids unchanged vs tip for awareness
const crypto = require('crypto');
function sha(obj) {
  return crypto.createHash('sha1').update(JSON.stringify(obj)).digest('hex').slice(0, 10);
}
for (const album of ['pregnancy_60', 'kids_48', 'diary_interior_brown', 'diary_interior_purple']) {
  console.log(
    album,
    'current',
    sha(currentJson[album]),
    'tipHad',
    sha(tipJson[album]),
    sha(currentJson[album]) === sha(tipJson[album]) ? 'SAME' : 'KEPT_OR_TAKEN',
  );
}
