#!/usr/bin/env node
/**
 * Сканирует albums/kids/DFAxx/first_page.png и генерирует:
 * - utils/kidsCoverDesigns.ts
 * - utils/kidsCoverPickerAssets.generated.ts
 *
 * Запуск: node scripts/generate-kids-cover-designs.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const kidsRoot = path.join(root, 'albums/kids');

function folderToId(folderName) {
  const num = folderName.replace(/^DFA/i, '');
  return `dfa_${num}`;
}

function numericSort(a, b) {
  const na = parseInt(a.replace(/^DFA/i, ''), 10);
  const nb = parseInt(b.replace(/^DFA/i, ''), 10);
  return na - nb;
}

const folders = fs
  .readdirSync(kidsRoot, { withFileTypes: true })
  .filter((d) => d.isDirectory() && /^DFA\d+$/i.test(d.name))
  .map((d) => d.name)
  .filter((name) => fs.existsSync(path.join(kidsRoot, name, 'first_page.png')))
  .sort(numericSort);

if (folders.length === 0) {
  throw new Error(`Не найдено обложек first_page.png в ${kidsRoot}`);
}

const pickerLines = folders.map((folder) => {
  const id = folderToId(folder);
  return `  '${id}': require('@/albums/kids/${folder}/first_page.png'),`;
});

const designLines = folders.map((folder) => {
  const id = folderToId(folder);
  return `  { id: '${id}', image: require('@/albums/kids/${folder}/first_page.png'), sku: '${folder}', title: '${folder}' },`;
});

const pickerOut = `/** Auto-generated by scripts/generate-kids-cover-designs.js — do not edit by hand */
import type { ImageSourcePropType } from 'react-native';

export const KIDS_FIRST_PAGE_BY_ID: Record<string, ImageSourcePropType> = {
${pickerLines.join('\n')}
};
`;

const designsOut = `/** Auto-generated by scripts/generate-kids-cover-designs.js — do not edit by hand */
/**
 * Дизайны обложки для раздела «Первые годы малыша» (albums/kids).
 * Используется только first_page.png. Тип обложки выбирается при экспорте.
 */
export const KIDS_COVER_DESIGNS = [
${designLines.join('\n')}
] as const;
`;

const pickerPath = path.join(root, 'utils/kidsCoverPickerAssets.generated.ts');
const designsPath = path.join(root, 'utils/kidsCoverDesigns.ts');

fs.writeFileSync(pickerPath, pickerOut);
fs.writeFileSync(designsPath, designsOut);

console.log(`Generated ${folders.length} kids cover designs`);
console.log('Written', designsPath);
console.log('Written', pickerPath);
