#!/usr/bin/env node
/**
 * Generates require() registry for design + variant preview PNGs (instant local load in dev).
 * node scripts/generate-preview-asset-registry.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const outFile = path.join(root, 'constants/generated/preview-asset-registry.ts');

const SCAN_DIRS = [
  'assets/pdfs/Блок БЕРЕМЕННОСТЬ 60 стр/design_previews',
  'assets/pdfs/Блок БЕРЕМЕННОСТЬ 60 стр/preview_variants',
  'assets/pdfs/Блок БОХО_ДЕТ.ФОТОАЛЬБОМ_ 48 стр/design_previews',
  'assets/pdfs/Блок БОХО_ДЕТ.ФОТОАЛЬБОМ_ 48 стр/preview_variants',
];

function collectPngs() {
  const entries = [];
  for (const relDir of SCAN_DIRS) {
    const absDir = path.join(root, relDir);
    if (!fs.existsSync(absDir)) continue;
    for (const file of fs.readdirSync(absDir)) {
      if (!file.endsWith('.png')) continue;
      const relPath = `${relDir}/${file}`.replace(/\\/g, '/');
      const requirePath = `../../${relPath}`;
      entries.push({ relPath, requirePath });
    }
  }
  entries.sort((a, b) => a.relPath.localeCompare(b.relPath));
  return entries;
}

function main() {
  const entries = collectPngs();
  const lines = entries.map(
    (e) => `  ${JSON.stringify(e.relPath)}: require(${JSON.stringify(e.requirePath)}),`,
  );

  const source = `/* eslint-disable @typescript-eslint/no-require-imports */
/** Auto-generated by scripts/generate-preview-asset-registry.js — do not edit. */
import { Image } from 'react-native';

const PREVIEW_ASSET_MODULES: Record<string, number> = {
${lines.join('\n')}
};

/** Instant file:// URI from Metro bundle (dev / local builds). */
export function resolveBundledPreviewUri(relativePath: string): string | null {
  const normalized = relativePath.replace(/^\\/+/g, '');
  const moduleId = PREVIEW_ASSET_MODULES[normalized];
  if (!moduleId) return null;
  const resolved = Image.resolveAssetSource(moduleId);
  return resolved?.uri ?? null;
}

export const PREVIEW_ASSET_COUNT = ${entries.length};
`;

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, source);
  console.log(`Wrote ${outFile} (${entries.length} preview PNGs)`);
}

main();
