/**
 * Diary-only data port. Never mutates pregnancy_60 / pregnancy_a5 / kids_48.
 * Tip 6858f3d is used only as a coordinate reference for diary_* albums.
 */
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const TIP = '6858f3d';
const DIARY = ['diary_interior_brown', 'diary_interior_purple'];
const PROTECTED = ['pregnancy_60', 'pregnancy_a5', 'kids_48'];

function sha(o) {
  return crypto.createHash('sha1').update(typeof o === 'string' ? o : JSON.stringify(o)).digest('hex').slice(0, 12);
}
function gitShow(file) {
  return execSync(`git show ${TIP}:${file}`, { encoding: 'utf8', maxBuffer: 80e6 });
}
function assertProtected(before, after, label) {
  for (const a of PROTECTED) {
    if (sha(before[a]) !== sha(after[a])) throw new Error(`PROTECTED CHANGED ${label} ${a}`);
  }
  console.log('OK protected', label);
}

// --- line-slots ---
{
  const p = path.join(ROOT, 'constants/line-slots.json');
  const before = JSON.parse(fs.readFileSync(p, 'utf8'));
  const tip = JSON.parse(gitShow('constants/line-slots.json'));
  const after = { ...before };
  for (const a of DIARY) {
    console.log('slots', a, sha(before[a]), '->', sha(tip[a]));
    after[a] = tip[a];
  }
  assertProtected(before, after, 'line-slots');
  fs.writeFileSync(p, JSON.stringify(after, null, 2) + '\n');
  const header = `// Auto-generated by scripts/generate-line-slots.js
// Do not edit manually.

export type NormalizedLineSlot = {
  x: number;
  y: number;
  width: number;
  height: number;
  hasLabel: boolean;
  continuationGroup: number;
  inputKind?: 'line' | 'block';
  textAnchorTop?: boolean;
  lineStrokeAtBottom?: boolean;
};

export const LINE_SLOTS = `;
  fs.writeFileSync(path.join(ROOT, 'constants/line-slots.ts'), header + JSON.stringify(after, null, 2) + ' as const;\n');
}

// --- line-guides ---
{
  const p = path.join(ROOT, 'constants/line-guides.json');
  const before = JSON.parse(fs.readFileSync(p, 'utf8'));
  const tip = JSON.parse(gitShow('constants/line-guides.json'));
  const after = { ...before };
  for (const a of DIARY) after[a] = tip[a];
  assertProtected(before, after, 'line-guides');
  fs.writeFileSync(p, JSON.stringify(after, null, 2) + '\n');
  const ts = fs.readFileSync(path.join(ROOT, 'constants/line-guides.ts'), 'utf8');
  const m = ts.match(/^([\s\S]*?export const LINE_GUIDES\s*=\s*)/);
  if (!m) throw new Error('line-guides.ts header missing');
  fs.writeFileSync(path.join(ROOT, 'constants/line-guides.ts'), m[1] + JSON.stringify(after, null, 2) + ' as const;\n');
}

// --- schemas: only diary albums ---
{
  function extract(src, album) {
    const startMarker = `  "${album}": [`;
    const start = src.indexOf(startMarker);
    if (start < 0) throw new Error('missing ' + album);
    let i = start + startMarker.length - 1;
    let depth = 0;
    for (; i < src.length; i++) {
      if (src[i] === '[') depth++;
      else if (src[i] === ']') {
        depth--;
        if (depth === 0) {
          let end = i + 1;
          if (src[end] === ',') end++;
          return { start, end, text: src.slice(start, end) };
        }
      }
    }
    throw new Error('unclosed ' + album);
  }
  const p = path.join(ROOT, 'constants/generated/album-page-schemas.ts');
  let out = fs.readFileSync(p, 'utf8');
  const tip = gitShow('constants/generated/album-page-schemas.ts');
  const beforeProt = {};
  for (const a of PROTECTED) beforeProt[a] = extract(out, a).text;
  for (const a of DIARY) {
    const cur = extract(out, a);
    const t = extract(tip, a);
    out = out.slice(0, cur.start) + t.text + out.slice(cur.end);
    console.log('schema', a, sha(cur.text), '->', sha(t.text));
  }
  for (const a of PROTECTED) {
    if (extract(out, a).text !== beforeProt[a]) throw new Error('PROTECTED SCHEMA ' + a);
  }
  fs.writeFileSync(p, out);
  console.log('OK protected schemas');
}

console.log('DONE data-only diary port');
